#ifndef TWCDEC_H
#define TWCDEC_H

#include <stdint.h>
#include "twcdefs.h"
#include "twsync.h"

/*
 * twcdec.h - From 119 soft bit values to a callsign.
 *
 * soft[idx], idx = 0..118, is in transmission order (Manchester pair
 * idx = chips 1+2*idx and 2+2*idx): positive means "second chip
 * louder than the first", i.e. a coded 1. Its magnitude is the
 * confidence (energy difference, in units of the noise level).
 *
 * Decoding is soft-decision maximum likelihood, group by group: each
 * of the 17 groups of 7 coded bits can only be one of 8 codewords, so
 * the codeword with the largest correlation is chosen (for group 0,
 * which carries the known sync bits, there is no choice at all; for
 * group 1, only 4 codewords are possible). If the resulting frame
 * fails the CRCs, the next most likely frames are tried in order
 * (swapping one, two or three groups to their runner-up codewords -
 * a small "list decoder"), up to list_max frames. The 19 CRC bits
 * then decide which one, if any, is the transmitted frame.
 */

typedef struct {
    int    n_tried;      /* frames checked against the CRC              */
    int    rank;         /* 0 = best frame passed directly, k = k-th one
                            down the list passed                        */
    double metric;       /* sum of the chosen codewords' correlations   */
    double loss;         /* metric given up vs. the best frame (0 if
                            rank 0)                                      */
} twc_decinfo_t;

/* Sum, over the 17 groups, of the best allowed codeword correlation:
 * the soft-decision likelihood score of the best frame. Used both as
 * the synchronization metric and for refinement. */
double twc_frame_metric(const float soft[TWC_NCODED]);

/* The classic frame's scores, for the receiver's search (twsync.h):
 * tw_spec_frame(&sp, TWC_NCODED, &twc_code_ops). */
extern const tw_code_ops_t twc_code_ops;

/* One candidate frame: the codeword chosen in each group. */
typedef struct {
    double metric;                       /* soft-decision score        */
    double loss;                         /* vs. the best frame         */
    unsigned char choice[TWC_NGROUPS]; /* 0..7 per group             */
} twc_frame_t;

/* The max_frames most likely frames, best first (rank 0 = best
 * codeword everywhere, then one, two or three groups swapped to a
 * runner-up). Returns how many were written. */
int twc_list_frames(const float soft[TWC_NCODED], int max_frames, twc_frame_t *out);

/* Descrambles a frame and checks sync bits, CRC16, CRC3 and callsign
 * fields. Returns 0 (call, packed filled) if valid, -1 otherwise. */
int twc_check_frame(const twc_frame_t *fr, char call[7], uint32_t *packed);

/* Returns 0 and fills call (6 chars + NUL, padding spaces kept) and
 * *packed on success, -1 if no frame within list_max passes the CRC
 * and callsign checks. info may be NULL. */
int twc_decode_soft(const float soft[TWC_NCODED], int list_max,
                      char call[7], uint32_t *packed, twc_decinfo_t *info);


/* "Twin" check. The classic frame's CRCs cannot tell apart a valid frame from a
 * few specific other valid frames that differ from it in 2 to 4
 * groups (twctwins.h, generated by tests/gen_twins.c - e.g. groups
 * 1 and 6 changed together in one precise way). Near the sensitivity
 * limit, that is exactly how false decodes happen: the true frame
 * arrives with a couple of damaged groups, and one of its CRC twins
 * looks valid. This returns, for a decoded frame, the smallest
 * soft-metric margin by which it beats any of its valid (and, if
 * requested, plausible) twins - +1e30 if it has none. A genuine
 * decode normally beats its twins by a wide margin (they differ from
 * it in at least 8 coded bits); a false one usually does not, since
 * the true frame is among its twins. twin_call (may be NULL) gets the
 * closest twin's callsign. */
double twc_twin_margin(const float soft[TWC_NCODED], const twc_frame_t *fr,
                         int plausible_only, char twin_call[7]);

#endif /* TWCDEC_H */
