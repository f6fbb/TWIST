/*
 * gen_twins.c - Finds the 2-, 3- and 4-group error patterns that the
 * classic CRCs cannot detect, and writes them as twctwins.h.
 *
 * A pattern is a set of groups and, for each, the XOR applied to the
 * group's 3 data bits (i.e. which other codeword is chosen). It is
 * kept only if it turns EVERY one of a dozen reference frames into
 * another frame that still passes the CRCs (the CRC is linear except
 * for its "zero byte -> 27/43" substitution, so such patterns are
 * universal). Group 0 (sync) is never touched, nor the known MSB of
 * group 1.
 *
 *   gcc -O2 -I. -o gen_twins tests/gen_twins.c twcenc.c twcdec.c
 *   ./gen_twins > twctwins.h
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "twcenc.h"
#include "twcdec.h"

#define NREF 12
/* A pattern is kept if it fools at least MINPASS of the NREF frames:
 * the CRC's zero-byte substitution makes a few patterns frame-
 * dependent, and the decoder re-checks each one on the actual frame
 * anyway, so the table only needs to be inclusive. */
#define MINPASS 1
static int hist[NREF + 1];
static const char *REFS[NREF] = { "F6FBB","OZ7IGY","9A1A","K1JT","EA5XYZ","DL0ABC",
                                  "F1HDI","F5ZZO","G4JNT","VK2ABC","2E0XYZ","JA1ABC" };
static twc_frame_t ref[NREF];

static void mkref(const char *c, twc_frame_t *fr)
{
    char norm[7]; uint32_t p; unsigned char v[TWC_NVEC]; int g, j;
    tw_normalize_call(c, norm); tw_pack_call(norm, &p); twc_build_vector(p, v);
    for (j = 0; j < TWC_NVEC; j++) v[j] ^= TWC_PSEUDO[j];
    for (g = 0; g < TWC_NGROUPS; g++) fr->choice[g] = (unsigned char)((v[3*g] << 2) | (v[3*g+1] << 1) | v[3*g+2]);
}

int main(void)
{
    int r, n, total = 0;
    for (r = 0; r < NREF; r++) mkref(REFS[r], &ref[r]);
    printf("/* twctwins.h - generated by tests/gen_twins.c, do not edit.\n");
    printf(" * Group error patterns the classic CRCs cannot detect: {ngroups,\n");
    printf(" * {group,xor}, ...}. See twcdec.c, twin check. */\n");
    printf("#ifndef TWCTWINS_H\n#define TWCTWINS_H\n\n");
    printf("typedef struct { unsigned char n; unsigned char g[4]; unsigned char x[4]; } twc_twin_t;\n\n");
    printf("static const twc_twin_t TWC_TWINS[] = {\n");
    for (n = 2; n <= 4; n++) {
        int idx[4], i, j;
        for (i = 0; i < n; i++) idx[i] = i + 1;
        for (;;) {
            int tot = 1, m;
            for (i = 0; i < n; i++) tot *= 7;
            for (m = 0; m < tot; m++) {
                int xs[4], mm = m, ok = 1, npass = 0;
                for (i = 0; i < n; i++) { xs[i] = 1 + mm % 7; mm /= 7; }
                for (i = 0; i < n; i++) if (idx[i] == 1 && (xs[i] & 4)) ok = 0;
                for (r = 0; r < NREF && ok; r++) {
                    twc_frame_t f = ref[r]; char c[7]; uint32_t pk;
                    for (i = 0; i < n; i++) f.choice[idx[i]] ^= (unsigned char)xs[i];
                    if (twc_check_frame(&f, c, &pk) == 0) npass++;
                }
                if (ok && npass > 0) hist[npass]++;
                if (ok && npass >= MINPASS) {
                    printf("    { %d, {", n);
                    for (i = 0; i < 4; i++) printf("%2d%s", i < n ? idx[i] : 0, i < 3 ? "," : "");
                    printf("}, {");
                    for (i = 0; i < 4; i++) printf("%d%s", i < n ? xs[i] : 0, i < 3 ? "," : "");
                    printf("} },\n");
                    total++;
                }
            }
            i = n - 1;
            while (i >= 0 && idx[i] == 16 - (n - 1 - i)) i--;
            if (i < 0) break;
            idx[i]++;
            for (j = i + 1; j < n; j++) idx[j] = idx[j - 1] + 1;
        }
    }
    printf("};\n#define TWC_NTWINS %d\n\n#endif\n", total);
    fprintf(stderr, "%d patterns; frames fooled per pattern:", total);
    for (r = 1; r <= NREF; r++) fprintf(stderr, " %d:%d", r, hist[r]);
    fprintf(stderr, "\n");
    return 0;
}
