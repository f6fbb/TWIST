/*
 * mktables.c - Generates twist_tables.h: the two TWIST LDPC codes
 * (parity-check lists for the decoder, generator rows for the
 * encoder), built once by PEG (ldpc_build, column weight 3, seed 1)
 * and then FROZEN in the table: the protocol is the table, not this
 * program. Re-run only to define a new code, never to "update" one.
 *
 *   gcc -O2 -I.. -o mktables mktables.c ../ldpc.c -lm && ./mktables > ../twist_tables.h
 */
#include <stdio.h>
#include <string.h>
#include "ldpc.h"

static void dump(const char *name, int n, int k)
{
    static ldpc_t c;
    int i, a, w, nw = 3;   /* always 3 words: n <= 192 */
    if (ldpc_build(&c, n, k, 3, 1) != 0) { fprintf(stderr, "build %d,%d failed\n", n, k); return; }
    printf("/* (%d, %d): %d checks, column weight 3, girth %d */\n", n, k, c.m, c.girth);
    printf("static const unsigned char %s_CHECK_DEG[%d] = {", name, c.m);
    for (i = 0; i < c.m; i++) printf("%s%s%d", i ? "," : "", i % 24 ? "" : "\n    ", c.ncheck_deg[i]);
    printf("\n};\n");
    {
        int tot = 0;
        for (i = 0; i < c.m; i++) tot += c.ncheck_deg[i];
        printf("/* variables of each check, concatenated (%d edges) */\n", tot);
        printf("static const unsigned char %s_CHECK_VAR[%d] = {", name, tot);
        tot = 0;
        for (i = 0; i < c.m; i++)
            for (a = 0; a < c.ncheck_deg[i]; a++, tot++)
                printf("%s%s%d", tot ? "," : "", tot % 16 ? "" : "\n    ", c.check_var[i][a]);
        printf("\n};\n");
    }
    printf("/* generator: row i = codeword of message bit i (bit j of the codeword\n"
           " * = bit (j %% 64) of word j / 64); message bit i is copied unchanged\n"
           " * to codeword position %s_PIVOT[i] */\n", name);
    printf("static const unsigned long long %s_G[%d][%d] = {\n", name, k, nw);
    for (i = 0; i < k; i++) {
        printf("    {");
        for (w = 0; w < nw; w++) printf("%s0x%016llxULL", w ? "," : "", (unsigned long long)c.G[i].w[w]);
        printf("},\n");
    }
    printf("};\n");
    printf("static const unsigned char %s_PIVOT[%d] = {", name, k);
    for (i = 0; i < k; i++) printf("%s%s%d", i ? "," : "", i % 24 ? "" : "\n    ", c.pivot[i]);
    printf("\n};\n\n");
}

int main(void)
{
    printf("/*\n * twist_tables.h - TWIST LDPC codes. GENERATED by tools/mktables.c,\n"
           " * then frozen: these tables DEFINE the protocol (TWIST v1).\n"
           " * Do not regenerate to \"update\" them - any change makes a new,\n"
           " * incompatible protocol.\n */\n#ifndef TWIST_TABLES_H\n#define TWIST_TABLES_H\n\n");
    printf("#define TWS_N 119\n#define TWS_K 44\n#define TWL_N 160\n#define TWL_K 69\n\n");
    dump("TWS", 119, 44);
    dump("TWL", 160, 69);
    printf("#endif\n");
    return 0;
}
